#!/usr/bin/env node
// build-seed.mjs — reads every seed/formats/*.json and writes gas/SeedData.gs
// (var SEED_FORMATS = [...]) so Admin.gs's adminSeedFormats() can use it.
// Re-run with `npm run build:seed` whenever a seed format file changes.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const seedDir = path.join(root, 'seed', 'formats');
const outFile = path.join(root, 'gas', 'SeedData.gs');

const files = readdirSync(seedDir)
  .filter((f) => f.endsWith('.json'))
  .sort();

const specs = files.map((f) => JSON.parse(readFileSync(path.join(seedDir, f), 'utf8')));

const contents =
  '// GENERATED by scripts/build-seed.mjs — do not edit\n' +
  'var SEED_FORMATS = ' + JSON.stringify(specs, null, 2) + ';\n';

writeFileSync(outFile, contents, 'utf8');
console.log('Wrote ' + outFile + ' with ' + specs.length + ' format(s): ' + specs.map((s) => s.id).join(', '));
